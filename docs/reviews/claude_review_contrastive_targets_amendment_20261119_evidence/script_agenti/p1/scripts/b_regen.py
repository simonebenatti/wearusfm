import json, sys, hashlib
from pathlib import Path
ROOT = Path(sys.argv[1])
import contrastive_prepare as P
baseline = P._read(P.BASELINE)
print('baseline sha ok', P._pin(P.BASELINE)['sha256'] == P.BASELINE_SHA256)
configs = P.build_review_configs(baseline)
prep = json.loads((ROOT / 'results/infra/contrastive_targets_20261118/review_configs/preparation.json').read_text())
print('preparation keys', sorted(prep), prep.get('status'), prep.get('training_approved'))
for name, cfg in configs.items():
    path = ROOT / f'results/infra/contrastive_targets_20261118/review_configs/{name}.config.json'
    text = json.dumps(cfg, indent=2, allow_nan=False) + '\n'
    saved = path.read_text()
    pin = prep['configs'][name]
    print(name, 'bytes_equal', text == saved, 'dict_equal', json.loads(saved) == cfg,
          'pin_sha_ok', hashlib.sha256(saved.encode()).hexdigest() == pin['sha256'], 'pin_path', pin['path'], 'bytes', pin['bytes'] == len(saved.encode()))
print('baseline pin', prep['baseline'])
# historical configs regenerated by the historical recipe (with_historical windows): build_review_configs minus the three changes
import copy
for name in ('C0','CN','CR','calibration'):
    old = json.loads((ROOT / f'results/infra/contrastive_comparison_20261116/configs/{name}.config.json').read_text())
    regen = copy.deepcopy(configs[name])
    del regen['loader']['rms_window_ms']; del regen['loader']['ms_fast_window_ms']; regen['target_version'] = 'step1_psd_power_shape_energy_v1'
    print('historical', name, 'equal after reverting three declared fields:', regen == old)
