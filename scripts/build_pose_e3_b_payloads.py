def embed(path):
    source = path.read_bytes()
    delimiter = 'WEARUSFM_E3_' + path.stem.upper()
    text = source.decode('utf-8')
    if not text.endswith('\n') or '\n' + delimiter + '\n' in text:
        raise ValueError('invalid embedded source delimiter/newline')
    digest = hashlib.sha256(source).hexdigest()
    return f'cat > "$E3_TMP_DIR/{path.name}" <<\'{delimiter}\'\n{text}{delimiter}\n', digest


def build(mode):
    names = ['pose_e3_b_extract.py'] if mode == 'extract' else ['pose_e3_b.py', 'pose_dynamics.py']
    payload, hashes = PREFIX, {}
    for name in names:
        block, digest = embed(ROOT / 'scripts' / name)
        payload += block
        hashes[name] = digest
    payload += '''python3 - "$E3_TMP_DIR" <<'WEARUSFM_E3_HASH_CHECK'
from pathlib import Path
import hashlib, sys
root = Path(sys.argv[1])
'''
    for name, digest in hashes.items():
        payload += f"assert hashlib.sha256((root / {name!r}).read_bytes()).hexdigest() == {digest!r}, 'source hash mismatch'\n"
    if mode == 'report':
        for path, digest in ((VAL_PROVENANCE, 'fe619d100b33618e0081fbbc151401d22f4a0dc5f300a2ce164d356f30319c3e'),
                             (REFERENCE, 'c624a13c1d028a16c17237853d91df3ca29159f5d80088ccede4c9368a9d9c74')):
            payload += f"assert hashlib.sha256(Path({path!r}).read_bytes()).hexdigest() == {digest!r}, 'reference hash mismatch'\n"
    payload += "print('E3 source and reference hashes verified', flush=True)\nWEARUSFM_E3_HASH_CHECK\n"
    if mode == 'extract':
        payload += f'''python3 "$E3_TMP_DIR/pose_e3_b_extract.py" \\
  --checkpoint '{CHECKPOINT}' --out '{TRAIN}' --r3c-train '{R3C_TRAIN}' \\
  --source-sha256 {hashes['pose_e3_b_extract.py']} --wrapper-sha256 "$WRAPPER_SHA256"
'''
    else:
        payload += f'''python3 "$E3_TMP_DIR/pose_e3_b.py" \\
  --train '{TRAIN}' --val '{VAL}' --checkpoint '{CHECKPOINT}' \\
  --out '{REPORT}' --predictions-out '{PREDICTIONS}' \\
  --train-provenance '{TRAIN}.extract_provenance.json' --val-provenance '{VAL_PROVENANCE}' \\
  --reference-dynamics '{REFERENCE}' \\
  --analysis-source-sha256 {hashes['pose_e3_b.py']} --wrapper-sha256 "$WRAPPER_SHA256"
'''
    return payload.encode('utf-8')


if __name__ == '__main__':
    for mode in ('extract', 'report'):
        path = ROOT / 'scripts' / 'slurm' / f'pose_e3_b_{mode}.sbatch'
        content = build(mode)
        path.write_bytes(content)
        print(f'{path.name}: {hashlib.sha256(content).hexdigest()}')
