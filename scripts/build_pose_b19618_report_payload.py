"""Embed B19618 report plus the unchanged frozen dynamics/ridge modules.

Inputs are passed as base64 UTF-8 JSON argv in B19618_REPORT_ARGS_B64. Only the
report's CLI paths are variable; source hashes are generated and checked here.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
FROZEN = {'pose_dynamics.py':'5e5ff2c8b27d5692a064534f793924ddf5463c7bab13ccf75356c0950d9dd5b8',
          'pose_e3_b.py':'859dc19b7867a9597fe7fe868cde8833471a1db7da018113809e6a6fda831782'}


def build():
    sources={name:(ROOT/'scripts'/name).read_text() for name in ('pose_b19618_report.py',*FROZEN)}
    hashes={name:hashlib.sha256(source.encode()).hexdigest() for name,source in sources.items()}
    for name,digest in FROZEN.items():
        if hashes[name]!=digest:
            raise ValueError('frozen source changed: '+name)
    prefix='''#!/bin/bash
# Generated by scripts/build_pose_b19618_report_payload.py; submit on stdin.
#SBATCH -A IscrB_WearUsFM
#SBATCH -p lrd_all_serial
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --mem=30G
#SBATCH --time=01:00:00
#SBATCH -o /leonardo_work/IscrB_WearUsFM/wearusfm_runs/logs/pose_b19618_report_%j.out
#SBATCH -e /leonardo_work/IscrB_WearUsFM/wearusfm_runs/logs/pose_b19618_report_%j.out
set -euo pipefail
: "${CODE_DIR:?}" "${EXPECTED_SHA:?}" "${WRAPPER_SHA256:?}" "${WORK:?}" "${B19618_REPORT_ARGS_B64:?}"
[ "$EXPECTED_SHA" = 24139ab901c052357a46a65bc20466f2eb1e8358 ] || exit 2
source "$CODE_DIR/scripts/slurm/lib_code_dir.sh"
code_dir_setup
module purge
module load profile/deeplrn
module load cineca-ai/4.3.0
source "$WORK/venv_wearusfm/bin/activate"
export OMP_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}" OPENBLAS_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}"
export MKL_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}" PYTHONDONTWRITEBYTECODE=1
B19618_REPORT_TMP=$(mktemp -d "${TMPDIR:-/tmp}/wearusfm-b19618-report.XXXXXX")
trap 'rm -f -- "$B19618_REPORT_TMP/pose_b19618_report.py" "$B19618_REPORT_TMP/pose_dynamics.py" "$B19618_REPORT_TMP/pose_e3_b.py"; rmdir -- "$B19618_REPORT_TMP"' EXIT
'''
    payload=prefix
    for name,source in sources.items():
        delimiter='WEARUSFM_B19618_'+name.upper().replace('.','_')
        if not source.endswith('\n') or '\n'+delimiter+'\n' in source:
            raise ValueError('invalid embedded source newline/delimiter')
        payload+=f'cat > "$B19618_REPORT_TMP/{name}" <<\'{delimiter}\'\n'+source+delimiter+'\n'
    driver='''python3 - "$B19618_REPORT_TMP" <<'WEARUSFM_B19618_REPORT_DRIVER'
import base64,hashlib,json,os,subprocess,sys
from pathlib import Path
folder=Path(sys.argv[1])
hashes=EMBEDDED_HASHES
for name,digest in hashes.items():
    if hashlib.sha256((folder/name).read_bytes()).hexdigest()!=digest:
        raise ValueError('payload source SHA mismatch: '+name)
args=json.loads(base64.b64decode(os.environ['B19618_REPORT_ARGS_B64'],validate=True).decode('utf-8'))
if not (isinstance(args,list) and args and all(isinstance(x,str) for x in args)):
    raise ValueError('B19618_REPORT_ARGS_B64 must encode a JSON string array')
if any(x.split('=',1)[0] in ('--source-sha256','--wrapper-sha256') for x in args):
    raise ValueError('source/wrapper hashes are supplied by wrapper')
raise SystemExit(subprocess.run([sys.executable,str(folder/'pose_b19618_report.py'),*args,'--source-sha256',hashes['pose_b19618_report.py'],'--wrapper-sha256',os.environ['WRAPPER_SHA256']]).returncode)
WEARUSFM_B19618_REPORT_DRIVER
'''.replace('EMBEDDED_HASHES',repr(hashes))
    return (payload+driver).encode()


if __name__=='__main__':
    payload=build()
    target=ROOT/'scripts/slurm/pose_b19618_report.sbatch'
    target.write_bytes(payload)
    print(f'{target.name}: {hashlib.sha256(payload).hexdigest()}')
