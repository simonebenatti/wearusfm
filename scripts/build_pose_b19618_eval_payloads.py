"""Build one source-hashed stdin wrapper for B19618 extraction/probe/compare.

B19618_ARGS_B64 is base64 of a UTF-8 JSON array of CLI strings. Arguments never pass through a
shell parser. Submission chooses GPU overrides for extraction; defaults are the
8-core, 30GB, four-hour CPU probe cap.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]


def build():
    source = (ROOT/'scripts/pose_b19618_eval_guard.py').read_text()
    delimiter = 'WEARUSFM_B19618_EVAL_SOURCE'
    if not source.endswith('\n') or '\n'+delimiter+'\n' in source:
        raise ValueError('invalid embedded source newline/delimiter')
    digest = hashlib.sha256(source.encode()).hexdigest()
    prefix = '''#!/bin/bash
# Generated by scripts/build_pose_b19618_eval_payloads.py; submit on stdin.
# Default CPU probe cap. Pose/channel submissions MUST override partition,
# GPU, memory and walltime according to the frozen plan; compare uses CPU.
#SBATCH -A IscrB_WearUsFM
#SBATCH -p lrd_all_serial
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=8
#SBATCH --mem=30G
#SBATCH --time=04:00:00
#SBATCH -o /leonardo_work/IscrB_WearUsFM/wearusfm_runs/logs/pose_b19618_eval_%j.out
#SBATCH -e /leonardo_work/IscrB_WearUsFM/wearusfm_runs/logs/pose_b19618_eval_%j.out
set -euo pipefail
: "${CODE_DIR:?}" "${EXPECTED_SHA:?}" "${WRAPPER_SHA256:?}" "${WORK:?}" "${B19618_ARGS_B64:?}"
[ "$EXPECTED_SHA" = 24139ab901c052357a46a65bc20466f2eb1e8358 ] || exit 2
source "$CODE_DIR/scripts/slurm/lib_code_dir.sh"
code_dir_setup
module purge
module load profile/deeplrn
module load cineca-ai/4.3.0
source "$WORK/venv_wearusfm/bin/activate"
export OMP_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}" OPENBLAS_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}"
export MKL_NUM_THREADS="${SLURM_CPUS_PER_TASK:-8}" PYTHONDONTWRITEBYTECODE=1
B19618_EVAL_TMP=$(mktemp -d "${TMPDIR:-/tmp}/wearusfm-b19618-eval.XXXXXX")
trap 'rm -f -- "$B19618_EVAL_TMP/pose_b19618_eval_guard.py"; rmdir -- "$B19618_EVAL_TMP"' EXIT
'''
    suffix = '''python3 - "$B19618_EVAL_TMP/pose_b19618_eval_guard.py" EXPECTED_SOURCE_DIGEST <<'WEARUSFM_B19618_EVAL_DRIVER'
import base64,hashlib,json,os,subprocess,sys
from pathlib import Path
source,digest=Path(sys.argv[1]),sys.argv[2]
if hashlib.sha256(source.read_bytes()).hexdigest()!=digest:
    raise ValueError('payload source SHA mismatch')
args=json.loads(base64.b64decode(os.environ['B19618_ARGS_B64'],validate=True).decode('utf-8'))
if not (isinstance(args,list) and args and all(isinstance(x,str) for x in args)):
    raise ValueError('B19618_ARGS_B64 must encode a JSON string array')
if any(x.split('=',1)[0] in ('--source-sha256','--wrapper-sha256') for x in args):
    raise ValueError('source/wrapper hashes are supplied by wrapper')
raise SystemExit(subprocess.run([sys.executable,str(source),*args,'--source-sha256',digest,'--wrapper-sha256',os.environ['WRAPPER_SHA256']]).returncode)
WEARUSFM_B19618_EVAL_DRIVER
'''.replace('EXPECTED_SOURCE_DIGEST',digest)
    return (prefix+f'cat > "$B19618_EVAL_TMP/pose_b19618_eval_guard.py" <<\'{delimiter}\'\n'+source+delimiter+'\n'+suffix).encode()


if __name__=='__main__':
    payload=build()
    target=ROOT/'scripts/slurm/pose_b19618_eval.sbatch'
    target.write_bytes(payload)
    print(f'{target.name}: {hashlib.sha256(payload).hexdigest()}')
